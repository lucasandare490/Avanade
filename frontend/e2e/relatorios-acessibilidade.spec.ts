import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import axe from 'axe-core';
const senha=readFileSync('../backend/.local/demo-password','utf8').trim();
test('relatórios: vazio, erro recuperável, dados, CSV e acessibilidade',async({page})=>{
 await page.goto('/');
 await page.getByLabel('E-mail',{exact:true}).fill('gerente1@demo.local');
 await page.getByLabel('Senha',{exact:true}).fill(senha);
 await page.getByRole('button',{name:'Entrar',exact:true}).click();
 await expect(page.locator('main#conteudo')).toBeVisible();
 await page.evaluate(()=>location.hash='/relatorios');
 await page.getByLabel('Data inicial',{exact:true}).fill('2000-01-01');
 await page.getByLabel('Data final',{exact:true}).fill('2000-01-02');
 await page.getByRole('button',{name:'Consultar relatório'}).click();
 await expect(page.getByText('Nenhum registro neste período.')).toBeVisible();
 await page.route('**/api/v1/reports/**',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({code:'UNAVAILABLE',message:'Serviço temporariamente indisponível.'})}));
 await page.getByRole('button',{name:'Consultar relatório'}).click();
 await expect(page.getByRole('heading',{name:'Não foi possível gerar o relatório'})).toBeVisible();
 await page.unroute('**/api/v1/reports/**');
 await page.getByRole('button',{name:'Tentar novamente',exact:true}).click();
 await expect(page.getByText('Nenhum registro neste período.')).toBeVisible();
 const today=new Intl.DateTimeFormat('en-CA',{timeZone:'America/Recife',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
 await page.getByLabel('Data inicial',{exact:true}).fill(today);
 await page.getByLabel('Data final',{exact:true}).fill(today);
 await page.getByRole('button',{name:'Consultar relatório'}).click();
 await expect(page.getByRole('table')).toBeVisible();
 const download=page.waitForEvent('download');
 await page.getByRole('button',{name:'Baixar relatório completo (CSV)'}).click();
 expect((await download).suggestedFilename()).toContain('relatorio-sales');
 await page.addScriptTag({content:axe.source});
 const result=await page.evaluate(async()=>await (window as any).axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}}));
 expect(result.violations.map((v:any)=>({id:v.id,nodes:v.nodes.map((n:any)=>n.target)}))).toEqual([]);
});
